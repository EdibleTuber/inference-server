# tests/test_bootstrap_profiles.py
"""The profiles shipped in config/models/ (Task 6): each one validates and
renders exactly what the host runs today, read from the live sidecars, slot
env files and unit ExecStart on 2026-10-30 and re-read 2026-11-01. Where a
sidecar was silent the value is llama.cpp b11136's default.

The gguf files are stubbed in tmp: these tests check the profiles, not the
host's models dir.
"""
from pathlib import Path

import pytest

from manager.profiles import load_profiles, render_model_env

REPO = Path(__file__).resolve().parent.parent
PROFILES = REPO / "config" / "models"
SLOTS = ["main", "egpu"]
MODELS = "/opt/llama/models"

# Every profile carries these: --jinja for tool calling, and
# --ctx-checkpoints 4 (the old units passed both in ExecStart).
COMMON = "--jinja --ctx-checkpoints 4 --n-predict 32768"

EXPECTED = {
    "Qwen3.8-27B-UD-Q6_K": {
        "home": "main",
        "sampling": "--temp 1.0 --top-k 20 --top-p 0.95 --min-p 0.0 "
                    "--presence-penalty 0.0 --frequency-penalty 0.0 --repeat-penalty 1.0",
        "flags": COMMON + " --spec-type draft-mtp --spec-draft-n-max 1",
    },
    "Qwen3.6-35B-A3B-UD-IQ4_NL_XL": {
        "home": "egpu",
        "sampling": "--temp 0.6 --top-k 20 --top-p 0.95 --min-p 0.05 "
                    "--presence-penalty 0.0 --frequency-penalty 0.0 --repeat-penalty 1.0",
        "flags": COMMON,
    },
    "gemma-4-26b-a4b-it-q4_k_m": {
        "home": "egpu",
        # The GGUF's general.sampling.* sets only temp, top_k and top_p, so
        # min_p is b11136's default, as for Qwen3.6.
        "sampling": "--temp 1.0 --top-k 64 --top-p 0.95 --min-p 0.05 "
                    "--presence-penalty 0.0 --frequency-penalty 0.0 --repeat-penalty 1.0",
        "flags": COMMON,
    },
}


@pytest.fixture(scope="module")
def shipped(tmp_path_factory):
    models = tmp_path_factory.mktemp("models")
    for toml in PROFILES.glob("*.toml"):
        (models / f"{toml.stem}.gguf").write_bytes(b"GGUF")
    return load_profiles(str(PROFILES), SLOTS, str(models))


def test_every_shipped_profile_validates(shipped):
    assert shipped.errors == {}


@pytest.mark.parametrize("name", EXPECTED)
def test_the_profile_is_shipped_under_its_exact_gguf_stem(shipped, name):
    profile = shipped.get(name)
    assert profile is not None, sorted(p.name for p in shipped.profiles.values())
    assert profile.name == name


@pytest.mark.parametrize("name", EXPECTED)
def test_the_profile_has_one_section_its_home(shipped, name):
    profile = shipped.get(name)
    assert profile.home == EXPECTED[name]["home"]
    assert list(profile.sections) == [EXPECTED[name]["home"]]


@pytest.mark.parametrize("name", EXPECTED)
def test_the_profile_renders_todays_command_line(shipped, name):
    profile = shipped.get(name)
    section = profile.section(profile.home)
    want = EXPECTED[name]
    assert render_model_env(profile, section, MODELS) == (
        f"# Generated by llama-manager from profile {name} [slots.{profile.home}]. "
        f"Every swap rewrites this file; do not edit.\n"
        f"MODEL_ARGS=--model {MODELS}/{name}.gguf --ctx-size 131072 --n-gpu-layers -1 "
        f"{want['sampling']} {want['flags']}\n")


def _comments(name: str) -> str:
    text = (PROFILES / f"{name}.toml").read_text(encoding="utf-8")
    return "\n".join(line for line in text.splitlines() if line.lstrip().startswith("#"))


@pytest.mark.parametrize("name", EXPECTED)
def test_every_profile_explains_its_common_flags(name):
    comments = _comments(name)
    assert "23181" in comments          # the --ctx-checkpoints issue
    assert "tool" in comments           # --jinja is required for tool calling


def test_the_qwen38_profile_keeps_its_mtp_and_kv_cache_notes():
    comments = _comments("Qwen3.8-27B-UD-Q6_K")
    assert "MTP" in comments
    assert "KV" in comments


def test_the_qwen36_profile_explains_min_p_and_the_auto_fit_warning():
    comments = _comments("Qwen3.6-35B-A3B-UD-IQ4_NL_XL")
    assert "min_p" in comments
    assert "common_params_fit_impl" in comments
    assert "nvidia-smi" in comments


def test_the_gemma_profile_names_where_its_sampling_comes_from():
    comments = _comments("gemma-4-26b-a4b-it-q4_k_m")
    assert "general.sampling" in comments
    assert "Q42" in comments
