@pytest.mark.parametrize("where,key", [
    ("top", "gguf"),
    ("section", "ctx"),
    ("sampling", "temperature"),
    ("verified", "by"),
])
def test_unknown_keys_are_errors(where, key):
    data = valid()
    data["slots"]["main"]["verified"] = {
        "date": "2026-10-31", "llama_cpp_build": 11136, "llama_cpp_commit": "057494f93"}
    target = {
        "top": data,
        "section": data["slots"]["main"],
        "sampling": data["slots"]["main"]["sampling"],
        "verified": data["slots"]["main"]["verified"],
    }[where]
    target[key] = 1
    assert_rejected(data, key)


# ---------------------------------------------------------------------------
# Types and ranges
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("path,value", [
    (("ctx_size",), True),
    (("n_gpu_layers",), False),
    (("sampling", "top_k"), True),
    (("sampling", "temp"), True),
])
def test_booleans_are_not_integers(path, value):
    """TOML true is a Python bool, and bool is an int subclass."""
    data = valid()
    target = data["slots"]["main"]
    for p in path[:-1]:
        target = target[p]
    target[path[-1]] = value
    assert_rejected(data, path[-1])


@pytest.mark.parametrize("path,value", [
    (("ctx_size",), 0),
    (("ctx_size",), 4096.0),
    (("n_gpu_layers",), -2),
    (("sampling", "top_k"), -1),
    (("sampling", "top_k"), 20.5),
    (("sampling", "temp"), "1.0"),
])
def test_out_of_range_or_mistyped_numbers_are_errors(path, value):
    data = valid()
    target = data["slots"]["main"]
    for p in path[:-1]:
        target = target[p]
    target[path[-1]] = value
    assert_rejected(data, path[-1])


def test_integer_sampling_values_are_accepted_for_floats():
    data = valid()
    data["slots"]["main"]["sampling"]["temp"] = 1
    data["slots"]["main"]["sampling"]["repeat_penalty"] = 1
    parse(data)


