def _cli(*args):
    return subprocess.run(
        [sys.executable, "-m", "manager.profiles", *args],
        capture_output=True, text=True,
        cwd=str(Path(__file__).resolve().parent.parent),
    )


def test_cli_check_passes_a_clean_directory(dirs):
    profiles, models = dirs
    write(profiles, models, "Good-Q4")
    r = _cli("check", str(profiles), "--slots", "main,egpu", "--models-dir", str(models))
    assert r.returncode == 0, r.stdout + r.stderr
    assert "1 profiles OK" in r.stdout


def test_cli_check_fails_and_names_the_bad_profile(dirs):
    profiles, models = dirs
    write(profiles, models, "Good-Q4")
    write(profiles, models, "Bad-Key", text=TOML.replace("ctx_size = 8192\n", ""))
    r = _cli("check", str(profiles), "--slots", "main,egpu", "--models-dir", str(models))
    assert r.returncode == 1
    assert "Bad-Key" in r.stdout + r.stderr
    assert "ctx_size" in r.stdout + r.stderr


def test_cli_render_prints_an_unverified_section(dirs):
    profiles, models = dirs
    write(profiles, models, "Good-Q4")
    r = _cli("render", str(profiles), "good-q4", "main",
             "--slots", "main,egpu", "--models-dir", str(models))
    assert r.returncode == 0, r.stderr
    assert r.stdout.splitlines()[1].startswith(
        f"MODEL_ARGS=--model {models}/Good-Q4.gguf --ctx-size 8192 ")
