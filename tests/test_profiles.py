@pytest.mark.parametrize("key", list(SAMPLING))
def test_every_sampling_key_is_required(key):
    data = valid()
    del data["slots"]["main"]["sampling"][key]
    assert_rejected(data, key)


def test_home_is_required():
    data = valid()
    del data["home"]
    assert_rejected(data, "home")


def test_at_least_one_section_is_required():
    data = valid()
    data["slots"] = {}
    assert_rejected(data, "slots")


