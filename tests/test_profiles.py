@pytest.mark.parametrize("flag", [
    "--model", "-m", "--ctx-size", "-c", "--n-gpu-layers", "--gpu-layers", "-ngl",
    "--host", "--port", "--device", "-dev", "--parallel", "-np", "--cache-ram", "-cram",
    "--temp", "--temperature", "--top-k", "--top-p", "--min-p",
    "--presence-penalty", "--frequency-penalty", "--repeat-penalty",
    "--ctx-size=4096",
])
def test_reserved_flags_are_rejected(flag):
    data = valid()
    data["slots"]["main"]["flags"] = ["--jinja", flag, "1"]
    assert_rejected(data, flag.split("=")[0])


@pytest.mark.parametrize("flags", [
    ["--n-predict 32768"],          # whitespace: two args inside one token
    ["--jinja\n"],                  # newline: a new env line
    ["--chat-template-kwargs", '{"a":1}'],
    ["--x", "it's"],
    ["--x", "$HOME"],
    ["--x", "a\\b"],
    ["--x", "`id`"],
    [""],
    ["--x", 1],                     # not a string
])
def test_flag_tokens_that_could_inject_into_the_env_file_are_rejected(flags):
    data = valid()
    data["slots"]["main"]["flags"] = flags
    assert_rejected(data, "flags")


def test_flags_must_be_a_list():
    data = valid()
    data["slots"]["main"]["flags"] = "--jinja"
    assert_rejected(data, "flags")


