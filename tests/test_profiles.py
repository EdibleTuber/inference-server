def test_render_is_exact():
    from manager.profiles import render_model_env
    p = parse(valid())
    text = render_model_env(p, p.section("main"), "/opt/llama/models")
    assert text == (
        "# Generated by llama-manager from profile Test-Model-Q4 [slots.main]. "
        "Every swap rewrites this file; do not edit.\n"
        "MODEL_ARGS=--model /opt/llama/models/Test-Model-Q4.gguf --ctx-size 131072 "
        "--n-gpu-layers -1 --temp 1.0 --top-k 20 --top-p 0.95 --min-p 0.0 "
        "--presence-penalty 0.0 --frequency-penalty 0.0 --repeat-penalty 1.0 "
        "--jinja --ctx-checkpoints 4\n"
        "ALPHA=x\n"
        "ZETA=1\n"
    )


def test_render_without_flags_or_env_has_only_the_required_args():
    from manager.profiles import render_model_env
    data = valid()
    del data["slots"]["main"]["flags"]
    del data["slots"]["main"]["env"]
    p = parse(data)
    lines = render_model_env(p, p.section("main"), "/m").splitlines()
    assert len(lines) == 2
    assert lines[1].endswith("--repeat-penalty 1.0")


