TOML = """\
home = "main"

[slots.main]
ctx_size = 8192
n_gpu_layers = -1

[slots.main.sampling]
temp = 1.0
top_k = 20
top_p = 0.95
min_p = 0.0
presence_penalty = 0.0
frequency_penalty = 0.0
repeat_penalty = 1.0
"""

VERIFIED = """
[slots.main.verified]
date = "2026-10-31"
llama_cpp_build = 11136
llama_cpp_commit = "057494f93"
"""


@pytest.fixture
def dirs(tmp_path):
    profiles = tmp_path / "models.d"
    models = tmp_path / "models"
    profiles.mkdir()
    models.mkdir()
    return profiles, models


def write(profiles: Path, models: Path, stem: str, text: str = TOML, gguf: bytes | None = b"GGUF"):
    (profiles / f"{stem}.toml").write_text(text)
    if gguf is not None:
        (models / f"{stem}.gguf").write_bytes(gguf)


def test_load_profile_names_it_from_the_file_stem(dirs):
    from manager.profiles import load_profile
    profiles, models = dirs
    write(profiles, models, "Good-Q4")
    p = load_profile(str(profiles / "Good-Q4.toml"), SLOTS, str(models))
    assert p.name == "Good-Q4"


@pytest.mark.parametrize("gguf", [None, b""], ids=["missing", "empty"])
def test_load_profile_requires_a_non_empty_gguf(dirs, gguf):
    from manager.profiles import ProfileError, load_profile
    profiles, models = dirs
    write(profiles, models, "Good-Q4", gguf=gguf)
    with pytest.raises(ProfileError, match="gguf"):
        load_profile(str(profiles / "Good-Q4.toml"), SLOTS, str(models))


def test_load_profiles_keeps_the_good_and_reports_the_bad(dirs):
    from manager.profiles import load_profiles
    profiles, models = dirs
    write(profiles, models, "Good-Q4")
    write(profiles, models, "No-Gguf", gguf=None)
    write(profiles, models, "Bad-Toml", text="home = [unclosed")
    write(profiles, models, "Bad-Key", text=TOML + "\n[slots.main.extra]\nx = 1\n")
    (profiles / "README.md").write_text("not a profile")

    ps = load_profiles(str(profiles), SLOTS, str(models))

    assert [p.name for p in ps.profiles.values()] == ["Good-Q4"]
    assert set(ps.errors) == {"No-Gguf", "Bad-Toml", "Bad-Key"}


def test_load_profiles_never_raises_on_a_missing_directory(tmp_path):
    from manager.profiles import load_profiles
    missing = str(tmp_path / "nope")
    ps = load_profiles(missing, SLOTS, str(tmp_path))
    assert ps.profiles == {}
    assert missing in ps.errors


def test_names_that_collide_case_insensitively_are_both_errors(dirs):
    from manager.profiles import load_profiles
    profiles, models = dirs
    write(profiles, models, "Model-Q4")
    write(profiles, models, "model-q4")
    ps = load_profiles(str(profiles), SLOTS, str(models))
    if len(list(profiles.glob("*.toml"))) < 2:
        pytest.skip("case-insensitive filesystem")
    assert ps.profiles == {}
    assert set(ps.errors) == {"Model-Q4", "model-q4"}


def test_profile_set_lookup_and_rosters(dirs):
    from manager.profiles import load_profiles
    profiles, models = dirs
    write(profiles, models, "Verified-Q4", text=TOML + VERIFIED)
    write(profiles, models, "Unverified-Q8")
    ps = load_profiles(str(profiles), SLOTS, str(models))

    assert ps.get("verified-q4.GGUF").name == "Verified-Q4"
    assert ps.get("/opt/llama/models/Verified-Q4.gguf").name == "Verified-Q4"
    assert ps.get("nothing") is None
    assert [p.name for p in ps.onboarded()] == ["Verified-Q4"]
    assert ps.home_models() == {"main": ["Unverified-Q8", "Verified-Q4"]}


