"""Phase 3, Task 1: per-model profiles are parsed, validated and rendered.

A profile is the whole of a model's configuration on a slot (Q29, Q33).
Anything it does not declare must be absent from what llama-server receives,
so validation is strict: unknown keys, missing required keys, bools posing as
ints, reserved flags, and any value that could inject into the generated env
file are all errors.
"""
import copy
import subprocess
import sys
from pathlib import Path

import pytest

SLOTS = ("main", "egpu")

SAMPLING = {
    "temp": 1.0, "top_k": 20, "top_p": 0.95, "min_p": 0.0,
    "presence_penalty": 0.0, "frequency_penalty": 0.0, "repeat_penalty": 1.0,
}


def valid() -> dict:
    return {
        "home": "main",
        "slots": {
            "main": {
                "ctx_size": 131072,
                "n_gpu_layers": -1,
                "flags": ["--jinja", "--ctx-checkpoints", "4"],
                "sampling": dict(SAMPLING),
                "env": {"ZETA": "1", "ALPHA": "x"},
            },
        },
    }


def parse(data, name="Test-Model-Q4"):
    from manager.profiles import parse_profile
    return parse_profile(name, data, SLOTS)


def assert_rejected(data, *needles, name="Test-Model-Q4"):
    from manager.profiles import ProfileError
    with pytest.raises(ProfileError) as exc:
        parse(data, name=name)
    for needle in needles:
        assert needle in str(exc.value), (needle, str(exc.value))


# ---------------------------------------------------------------------------
# Parsing a valid profile
# ---------------------------------------------------------------------------

def test_a_valid_profile_parses():
    from manager.profiles import SAMPLING_KEYS
    p = parse(valid())
    assert p.name == "Test-Model-Q4"
    assert p.home == "main"
    s = p.section("main")
    assert (s.slot, s.ctx_size, s.n_gpu_layers) == ("main", 131072, -1)
    assert s.flags == ("--jinja", "--ctx-checkpoints", "4")
    assert [k for k, _ in s.sampling] == list(SAMPLING_KEYS)
    assert s.env == (("ALPHA", "x"), ("ZETA", "1"))
    assert s.verified is None
    assert p.section("egpu") is None
    assert p.verified_slots() == ()


def test_sampling_keys_are_the_full_set():
    from manager.profiles import SAMPLING_KEYS
    assert SAMPLING_KEYS == ("temp", "top_k", "top_p", "min_p",
                             "presence_penalty", "frequency_penalty", "repeat_penalty")


def test_flags_and_env_are_optional():
    data = valid()
    del data["slots"]["main"]["flags"]
    del data["slots"]["main"]["env"]
    s = parse(data).section("main")
    assert (s.flags, s.env) == ((), ())


def test_verified_is_parsed():
    data = valid()
    data["slots"]["main"]["verified"] = {
        "date": "2026-10-31", "llama_cpp_build": 11136, "llama_cpp_commit": "057494f93"}
    p = parse(data)
    v = p.section("main").verified
    assert (v.date, v.llama_cpp_build, v.llama_cpp_commit) == ("2026-10-31", 11136, "057494f93")
    assert p.verified_slots() == ("main",)


